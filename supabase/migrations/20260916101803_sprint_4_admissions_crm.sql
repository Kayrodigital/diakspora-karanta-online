create or replace function public.recommend_classes_for_application(p_application_id uuid)
returns table(
  cohort_id uuid, cohort_name text, score integer, recommended boolean,
  reasons text[], exclusions text[], remaining_places integer, availability text
)
language sql stable security invoker set search_path = '' as $$
  with application as (
    select * from public.enrollment_applications a
    where a.id=p_application_id and private.can_read_admissions(a.organization_id)
  ), candidates as (
    select c.*, a.audience requested_audience, a.objective requested_objective,
      a.level requested_level, a.availability requested_availability,
      a.accompaniment_language requested_language, a.learner_birth_date,
      case when a.learner_birth_date is null then null
        else extract(year from age(current_date, a.learner_birth_date))::integer end requested_age,
      (select count(*) from public.learner_cohort_memberships m where m.cohort_id=c.id and m.status='active') active_count
    from public.cohorts c join application a on a.organization_id=c.organization_id
    where c.status='active'
  )
  select c.id, c.name,
    (case when c.audience=c.requested_audience then 35 else 0 end
      + case when c.objective=c.requested_objective then 25 else 0 end
      + case when c.requested_level='unsure' or c.level=c.requested_level then 15 else 0 end
      + case when c.session_period=c.requested_availability or c.delivery_format='on_demand' then 10 else 0 end
      + case when c.requested_language=any(c.teaching_languages) then 10 else 0 end
      + case when c.requested_age is null
          or ((c.age_min is null or c.requested_age>=c.age_min) and (c.age_max is null or c.requested_age<=c.age_max))
        then 5 else 0 end
      + case when c.enrollment_status='open' and (c.max_students is null or c.active_count<c.max_students) then 5 else 0 end)::integer score,
    (c.audience=c.requested_audience and c.objective=c.requested_objective
      and (c.requested_level='unsure' or c.level=c.requested_level)
      and c.enrollment_status in ('open','waitlist')
      and (c.starts_on is null or c.ends_on is null or c.ends_on>=current_date)
      and (c.requested_age is null or ((c.age_min is null or c.requested_age>=c.age_min) and (c.age_max is null or c.requested_age<=c.age_max)))
      and (c.max_students is null or c.active_count<c.max_students or c.enrollment_status='waitlist')) recommended,
    array_remove(array[
      case when c.audience=c.requested_audience then 'Public et règle de mixité compatibles' end,
      case when c.objective=c.requested_objective then 'Objectif pédagogique compatible' end,
      case when c.requested_level='unsure' or c.level=c.requested_level then 'Niveau compatible' end,
      case when c.session_period=c.requested_availability or c.delivery_format='on_demand' then 'Disponibilité compatible' end,
      case when c.requested_language=any(c.teaching_languages) then 'Langue compatible' end
      ,case when c.requested_age is null then 'Âge à confirmer'
        when (c.age_min is null or c.requested_age>=c.age_min) and (c.age_max is null or c.requested_age<=c.age_max)
        then 'Tranche d’âge compatible' end
    ],null),
    array_remove(array[
      case when c.audience<>c.requested_audience then 'Public ou règle de mixité incompatible' end,
      case when c.objective<>c.requested_objective then 'Objectif différent' end,
      case when c.requested_level<>'unsure' and c.level is distinct from c.requested_level then 'Niveau différent' end,
      case when c.session_period is distinct from c.requested_availability and c.delivery_format<>'on_demand' then 'Créneau différent' end,
      case when not(c.requested_language=any(c.teaching_languages)) then 'Langue non proposée' end,
      case when c.requested_age is not null and not ((c.age_min is null or c.requested_age>=c.age_min) and (c.age_max is null or c.requested_age<=c.age_max)) then 'Tranche d’âge incompatible' end,
      case when c.enrollment_status='closed' then 'Inscriptions fermées' end,
      case when c.max_students is not null and c.active_count>=c.max_students then 'Classe complète' end,
      case when c.ends_on is not null and c.ends_on<current_date then 'Classe terminée' end
    ],null),
    case when c.max_students is null then null else greatest(c.max_students-c.active_count,0)::integer end,
    case when c.enrollment_status='closed' then 'closed'
      when c.max_students is not null and c.active_count>=c.max_students then 'full'
      else c.enrollment_status end
  from candidates c
  order by recommended desc, score desc, c.starts_on nulls last, c.name;
$$;
