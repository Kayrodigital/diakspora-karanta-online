create or replace function private.guard_admission_application_update()
returns trigger language plpgsql security invoker set search_path = '' as $$
declare
  v_direction boolean := private.has_organization_role(old.organization_id, array['owner','admin'])
    or private.is_platform_administrator();
  v_commercial boolean := private.has_organization_role(old.organization_id, array['commercial']);
  v_classes boolean := private.has_organization_role(old.organization_id, array['class_manager']);
  v_pedagogy boolean := private.has_organization_role(old.organization_id, array['pedagogical_manager']);
  v_support boolean := private.has_organization_role(old.organization_id, array['support','technician']);
begin
  if current_user in ('postgres', 'service_role') or pg_trigger_depth() > 1 then return new; end if;
  if new.organization_id is distinct from old.organization_id
    or new.email is distinct from old.email
    or new.privacy_consent is distinct from old.privacy_consent then
    raise exception 'Les données d’origine de la demande ne peuvent pas être déplacées ou remplacées.';
  end if;
  if v_direction then return new; end if;
  if v_commercial and
    (to_jsonb(new) - array[
      'audience','objective','level','availability','accompaniment_language','applicant_name',
      'learner_name','phone','preferred_contact','notes','source','cohort_id','assigned_to',
      'status','next_action','follow_up_at','internal_notes','source_detail','proposed_cohort_id',
      'priority','close_outcome','close_reason','postponed_until','learner_birth_date',
      'first_contacted_at','updated_at'
    ]::text[]) =
    (to_jsonb(old) - array[
      'audience','objective','level','availability','accompaniment_language','applicant_name',
      'learner_name','phone','preferred_contact','notes','source','cohort_id','assigned_to',
      'status','next_action','follow_up_at','internal_notes','source_detail','proposed_cohort_id',
      'priority','close_outcome','close_reason','postponed_until','learner_birth_date',
      'first_contacted_at','updated_at'
    ]::text[]) then return new; end if;
  if v_classes and
    (to_jsonb(new) - array['proposed_cohort_id','status','next_action','follow_up_at','internal_notes','priority','updated_at']::text[]) =
    (to_jsonb(old) - array['proposed_cohort_id','status','next_action','follow_up_at','internal_notes','priority','updated_at']::text[])
    then return new; end if;
  if v_pedagogy and
    (to_jsonb(new) - array['objective','level','status','next_action','follow_up_at','internal_notes','updated_at']::text[]) =
    (to_jsonb(old) - array['objective','level','status','next_action','follow_up_at','internal_notes','updated_at']::text[])
    then return new; end if;
  if v_support and
    (to_jsonb(new) - array['next_action','follow_up_at','internal_notes','first_login_verified_at','updated_at']::text[]) =
    (to_jsonb(old) - array['next_action','follow_up_at','internal_notes','first_login_verified_at','updated_at']::text[])
    then return new; end if;
  raise exception 'Votre rôle ne permet pas cette modification.';
end;
$$;
revoke all on function private.guard_admission_application_update() from public, anon, authenticated;

create trigger enrollment_applications_guard_update
before update on public.enrollment_applications
for each row execute function private.guard_admission_application_update();

create or replace function private.prevent_recent_duplicate_application()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if exists (
    select 1
    from public.enrollment_applications existing
    where existing.organization_id = new.organization_id
      and existing.created_at >= now() - interval '24 hours'
      and existing.status <> 'closed'
      and lower(btrim(existing.email)) = lower(btrim(new.email))
      and lower(btrim(existing.learner_name)) = lower(btrim(new.learner_name))
  ) then
    raise exception using
      errcode = '23505',
      message = 'Une demande récente existe déjà pour cet élève.',
      hint = 'Retrouvez la demande existante ou réessayez après 24 heures.';
  end if;
  return new;
end;
$$;
revoke all on function private.prevent_recent_duplicate_application() from public, anon, authenticated;
create trigger enrollment_applications_prevent_recent_duplicate
before insert on public.enrollment_applications
for each row execute function private.prevent_recent_duplicate_application();

create or replace function private.log_admission_application_change()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_type text; v_summary text;
begin
  if new.status is distinct from old.status then
    v_type := case when new.status='closed' then 'closed' else 'stage_changed' end;
    v_summary := 'Étape : ' || old.status || ' → ' || new.status;
  elsif new.assigned_to is distinct from old.assigned_to then
    v_type := 'assigned'; v_summary := 'Responsable modifié';
  elsif new.proposed_cohort_id is distinct from old.proposed_cohort_id then
    v_type := 'class_proposed'; v_summary := 'Classe proposée modifiée';
  elsif new.follow_up_at is distinct from old.follow_up_at then
    v_type := 'follow_up_scheduled'; v_summary := 'Relance programmée';
  elsif new.first_login_verified_at is distinct from old.first_login_verified_at then
    v_type := 'first_login_verified'; v_summary := 'Première connexion vérifiée';
  else return new;
  end if;
  insert into public.admission_events(
    organization_id, application_id, actor_user_id, event_type, summary, metadata
  ) values (
    new.organization_id, new.id, auth.uid(), v_type, v_summary,
    jsonb_build_object('old_status',old.status,'new_status',new.status)
  );
  return new;
end;
$$;
revoke all on function private.log_admission_application_change() from public, anon, authenticated;
create trigger enrollment_applications_log_change
after update on public.enrollment_applications
for each row execute function private.log_admission_application_change();

create or replace function private.sync_application_payment_status()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  update public.enrollment_applications
  set payment_status = new.status, updated_at = now()
  where id = new.application_id;
  insert into public.admission_events(
    organization_id, application_id, actor_user_id, event_type, summary, metadata
  ) values (
    new.organization_id, new.application_id, auth.uid(), 'payment_changed',
    'Paiement : ' || coalesce(old.status, '—') || ' → ' || new.status,
    jsonb_build_object('payment_id',new.id,'expected_amount_cents',new.expected_amount_cents,'received_amount_cents',new.received_amount_cents)
  );
  return new;
end;
$$;
revoke all on function private.sync_application_payment_status() from public, anon, authenticated;
