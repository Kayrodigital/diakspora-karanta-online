CREATE OR REPLACE FUNCTION private.is_platform_administrator()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.platform_administrators AS administrator
    WHERE administrator.user_id = (SELECT auth.uid())
  );
$$;

CREATE OR REPLACE FUNCTION private.is_organization_member(p_organization_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT (SELECT auth.uid()) IS NOT NULL
    AND EXISTS (
      SELECT 1
      FROM public.organization_memberships AS membership
      WHERE membership.organization_id = p_organization_id
        AND membership.user_id = (SELECT auth.uid())
        AND membership.status = 'active'
    );
$$;

CREATE OR REPLACE FUNCTION private.has_organization_role(
  p_organization_id uuid,
  p_roles text[]
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT (SELECT auth.uid()) IS NOT NULL
    AND EXISTS (
      SELECT 1
      FROM public.organization_memberships AS membership
      WHERE membership.organization_id = p_organization_id
        AND membership.user_id = (SELECT auth.uid())
        AND membership.status = 'active'
        AND membership.role = ANY (p_roles)
    );
$$;

CREATE OR REPLACE FUNCTION private.is_linked_parent(
  p_organization_id uuid,
  p_learner_user_id uuid
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT (SELECT auth.uid()) IS NOT NULL
    AND EXISTS (
      SELECT 1
      FROM public.family_relationships AS relationship
      WHERE relationship.organization_id = p_organization_id
        AND relationship.parent_user_id = (SELECT auth.uid())
        AND relationship.learner_user_id = p_learner_user_id
        AND relationship.status = 'active'
    );
$$;

