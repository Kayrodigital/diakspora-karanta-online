CREATE TABLE IF NOT EXISTS public.organizations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL CHECK (char_length(name) BETWEEN 2 AND 120),
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  status text NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'suspended', 'archived')),
  logo_url text,
  primary_color text NOT NULL DEFAULT '#1E5631'
    CHECK (primary_color ~ '^#[0-9A-Fa-f]{6}$'),
  accent_color text NOT NULL DEFAULT '#C9932F'
    CHECK (accent_color ~ '^#[0-9A-Fa-f]{6}$'),
  default_locale text NOT NULL DEFAULT 'fr',
  enabled_locales text[] NOT NULL DEFAULT ARRAY['fr']::text[],
  custom_domain text UNIQUE,
  feature_flags jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.organization_memberships (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  role text NOT NULL CHECK (
    role IN (
      'owner',
      'admin',
      'technician',
      'pedagogical_manager',
      'teacher',
      'class_manager',
      'parent',
      'learner'
    )
  ),
  status text NOT NULL DEFAULT 'active'
    CHECK (status IN ('invited', 'active', 'suspended')),
  is_default boolean NOT NULL DEFAULT false,
  invited_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (organization_id, user_id, role)
);

CREATE UNIQUE INDEX IF NOT EXISTS organization_memberships_one_default_per_user
  ON public.organization_memberships (user_id)
  WHERE is_default AND status = 'active';

CREATE INDEX IF NOT EXISTS organization_memberships_organization_user_idx
  ON public.organization_memberships (organization_id, user_id)
  WHERE status = 'active';

CREATE TABLE IF NOT EXISTS public.family_relationships (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  parent_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  learner_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  relationship text NOT NULL DEFAULT 'guardian'
    CHECK (relationship IN ('parent', 'guardian')),
  status text NOT NULL DEFAULT 'active'
    CHECK (status IN ('pending', 'active', 'revoked')),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (parent_user_id <> learner_user_id),
  UNIQUE (organization_id, parent_user_id, learner_user_id)
);

CREATE TABLE IF NOT EXISTS public.platform_administrators (
