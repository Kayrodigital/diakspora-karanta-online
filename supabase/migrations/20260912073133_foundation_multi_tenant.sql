CREATE OR REPLACE FUNCTION private.homework_object_organization_id(p_name text)
RETURNS uuid
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
BEGIN
  RETURN (storage.foldername(p_name))[1]::uuid;
EXCEPTION WHEN invalid_text_representation OR array_subscript_error THEN
  RETURN NULL;
END;
$$;

